#!/usr/bin/env python3
"""Regenerate the page lists in wiki/index.md and wiki/learning.md from each
page's frontmatter, then lint the wiki. Run after every ingest:

    python3 scripts/sync.py

Only the text between the auto:start / auto:end markers is rewritten.
Exits 1 on errors (broken link or section link, title != filename, page
outside the five folders, bad status/type); orphans are warnings.
"""
import pathlib
import re
import sys

WIKI = pathlib.Path(__file__).resolve().parent.parent / "wiki"
FOLDERS = {  # folder -> heading, in display order
    "therapeutic-areas": "Therapeutic Areas",
    "clinical": "Clinical",
    "statistics": "Statistics",
    "trial-conduct": "Trial Conduct",
    "regulatory": "Regulatory",
}
META = {"index", "learning", "log"}
STATUSES = ("learned", "learning")
TYPES = {"concept", "therapeutic-area"}
START, END = "<!-- auto:start -->", "<!-- auto:end -->"

FENCE = re.compile(r"```.*?```", re.S)
CODE = re.compile(r"```.*?```|`[^`\n]*`", re.S)
LINK = re.compile(r"\[\[([^\]]+)\]\]")


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    pairs = (line.split(":", 1) for line in m.group(1).splitlines() if ":" in line)
    return {k.strip(): v.strip().strip('"') for k, v in pairs}


def links(text):
    """(target, anchor) for each wiki-link; the alias (| or table-escaped \\|) is dropped."""
    for raw in LINK.findall(CODE.sub("", text)):
        target, _, anchor = re.split(r"\\?\|", raw, maxsplit=1)[0].partition("#")
        yield target.strip(), anchor.strip()


def slug(heading):
    """Section anchor the way Quartz (github-slugger) builds it."""
    return re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")


def headings(text):
    return {slug(h) for h in re.findall(r"^#{1,6}\s+(.+?)\s*$", FENCE.sub("", text), re.M)}


def load():
    pages = {}  # filename stem -> (path relative to wiki/, frontmatter, text)
    for p in sorted(WIKI.rglob("*.md")):
        rel = p.relative_to(WIKI)
        if rel.parts[0] == "templates":
            continue
        text = p.read_text(encoding="utf-8")
        pages.setdefault(p.stem, []).append((rel, frontmatter(text), text))
    return pages


def bullets(stems):
    return "\n".join(f"- [[{s}]]" for s in sorted(stems, key=str.lower))


def content_in(content, folder):
    return [s for s, (rel, _, _) in content.items() if rel.parts[0] == folder]


def grouped(content, status=None):
    out = []
    for folder, heading in FOLDERS.items():
        stems = [s for s, (rel, fm, _) in content.items()
                 if rel.parts[0] == folder and (status is None or fm.get("status") == status)]
        if stems:
            out.append((heading, bullets(stems)))
    return out


def write_block(name, body, errors):
    p = WIKI / name
    text = p.read_text(encoding="utf-8")
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        errors.append(f"{name}: missing {START} / {END} markers")
        return
    new = text[: i + len(START)] + "\n" + body + "\n" + text[j:]
    if new != text:
        p.write_text(new, encoding="utf-8")


def main():
    errors, warnings = [], []
    pages = load()
    for stem, copies in pages.items():
        if len(copies) > 1:
            errors.append(f"duplicate page name '{stem}': " + ", ".join(str(c[0]) for c in copies))
    content = {s: c[0] for s, c in pages.items() if s not in META}

    counts = " · ".join(f"{len(content_in(content, f))} {h.lower()}" for f, h in FOLDERS.items())
    index = [f"**{len(content)} pages** — {counts}. _Lists below are generated by "
             "`scripts/sync.py`; don't edit them by hand._"]
    index += [f"## {h}\n\n{b}" for h, b in grouped(content)]
    write_block("index.md", "\n\n".join(index), errors)

    learning = ["_Generated from each page's `status:` by `scripts/sync.py`; don't edit by hand._"]
    for status, heading in (("learned", "Learned"), ("learning", "In Progress")):
        n = sum(fm.get("status") == status for _, fm, _ in content.values())
        learning.append(f"## {heading} ({n})")
        learning += [f"**{h}**\n\n{b}" for h, b in grouped(content, status)]
    write_block("learning.md", "\n\n".join(learning), errors)

    # Lint against the files as they now stand.
    pages = {s: c[0] for s, c in load().items()}
    inbound = dict.fromkeys(pages, 0)
    sections = {s: headings(text) for s, (_, _, text) in pages.items()}
    for stem, (rel, fm, text) in pages.items():
        if stem not in META:
            if len(rel.parts) != 2 or rel.parts[0] not in FOLDERS:
                errors.append(f"{rel}: not in one of the folders {', '.join(FOLDERS)}")
            if fm.get("title") != stem:
                errors.append(f"{rel}: title {fm.get('title')!r} != filename")
            if fm.get("status") not in STATUSES:
                errors.append(f"{rel}: status must be one of {', '.join(STATUSES)}")
            if fm.get("type") not in TYPES:
                errors.append(f"{rel}: type must be one of {', '.join(sorted(TYPES))}")
        for target, anchor in set(links(text)):
            target = target or stem
            if target not in pages:
                errors.append(f"{rel}: broken link [[{target}]]")
                continue
            if anchor and not anchor.startswith("^") and slug(anchor) not in sections[target]:
                errors.append(f"{rel}: broken section link [[{target}#{anchor}]]")
            if stem not in META and target != stem:
                inbound[target] += 1
    for stem, n in inbound.items():
        if n == 0 and stem not in META:
            warnings.append(f"{pages[stem][0]}: orphan (no other page links to it)")

    learned = sum(fm.get("status") == "learned" for s, (_, fm, _) in pages.items() if s not in META)
    print(f"synced index.md + learning.md: {len(pages) - len(META)} pages ({learned} learned)")
    for line in errors:
        print("ERROR  ", line)
    for line in warnings:
        print("WARN   ", line)
    if not errors and not warnings:
        print("lint: clean")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
